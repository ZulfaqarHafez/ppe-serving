"""Write tests/golden.hpp: Pillow reference values for the unit tests.

Resize goldens come from Pillow's Image.resize(..., Image.BILINEAR) on a small
synthetic image; the PNG byte arrays are encoded by Pillow. Re-run after a
Pillow upgrade to check the port still matches:

  python3 tests/make_golden.py > tests/golden.hpp
"""
import io

import numpy as np
from PIL import Image, __version__ as pil_version

W, H = 13, 7


def source():
    return np.array([[[(x * 37 + y * 91 + c * 53) % 256 for c in range(3)] for x in range(W)]
                     for y in range(H)], dtype=np.uint8)


def png(arr, mode):
    b = io.BytesIO()
    Image.fromarray(arr, mode).save(b, "PNG")
    return list(b.getvalue())


def array(name, values, ctype="std::uint8_t"):
    body = ", ".join(str(v) for v in values)
    return f"inline constexpr std::array<{ctype}, {len(values)}> {name} = {{{body}}};\n"


def main():
    img = Image.fromarray(source(), "RGB")
    out = [
        "// Generated by tests/make_golden.py with Pillow " + pil_version + ". Do not edit.\n",
        "// clang-format off\n#ifndef PPE_TESTS_GOLDEN_HPP\n#define PPE_TESTS_GOLDEN_HPP\n\n",
        "#include <array>\n#include <cstdint>\n\nnamespace golden {\n\n",
        f"// Source: {W}x{H} RGB, pixel (x, y, c) = (x * 37 + y * 91 + c * 53) % 256.\n",
        f"inline constexpr int kSrcWidth = {W};\ninline constexpr int kSrcHeight = {H};\n",
    ]
    for w, h in [(5, 3), (20, 11), (13, 4)]:
        r = np.asarray(img.resize((w, h), Image.BILINEAR)).flatten()
        out.append(f"// Image.resize(({w}, {h}), Image.BILINEAR)\n")
        out.append(array(f"kResize{w}x{h}", r))
    rgb = np.array([[[255, 0, 0], [0, 255, 0], [0, 0, 255]],
                    [[10, 20, 30], [40, 50, 60], [70, 80, 90]]], dtype=np.uint8)
    out.append("// 3x2 RGB PNG and its pixels\n" + array("kPngRgb", png(rgb, "RGB")))
    out.append(array("kPngRgbPixels", rgb.flatten()))
    grey = np.array([[0, 100], [200, 255]], dtype=np.uint8)
    out.append("// 2x2 greyscale PNG and its pixels\n" + array("kPngGrey", png(grey, "L")))
    out.append(array("kPngGreyPixels", grey.flatten()))
    rgba = np.array([[[1, 2, 3, 0], [4, 5, 6, 128]], [[7, 8, 9, 255], [10, 11, 12, 64]]],
                    dtype=np.uint8)
    out.append("// 2x2 RGBA PNG; Image.convert('RGB') drops alpha\n" + array("kPngRgba", png(rgba, "RGBA")))
    out.append(array("kPngRgbaAsRgb", np.asarray(Image.fromarray(rgba, "RGBA").convert("RGB")).flatten()))
    out.append("\n}  // namespace golden\n\n#endif  // PPE_TESTS_GOLDEN_HPP\n")
    print("".join(out), end="")


if __name__ == "__main__":
    main()
